import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import ts from 'typescript';

const root = process.cwd();
const registryPath = path.join(root, 'lib/appearance/registry.ts');
const assetDirectory = path.join(root, 'public/fonts');
const cssPath = path.join(root, 'app/fonts.generated.css');
const lockPath = path.join(root, 'config/google-fonts.lock.json');

const registrySource = await readFile(registryPath, 'utf8');
const sourceFile = ts.createSourceFile(registryPath, registrySource, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);

const fonts = [];
const literal = (node) => (node && ts.isStringLiteral(node) ? node.text : undefined);

function visit(node) {
  if (ts.isCallExpression(node) && ts.isIdentifier(node.expression) && node.expression.text === 'font') {
    const id = literal(node.arguments[0]);
    const family = literal(node.arguments[1]);
    const license = literal(node.arguments[5]) ?? 'OFL-1.1';
    const weightsNode = node.arguments[6];
    const weights = weightsNode && ts.isArrayLiteralExpression(weightsNode)
      ? weightsNode.elements.flatMap((element) => ts.isNumericLiteral(element) ? [Number(element.text)] : [])
      : [400, 600, 700];
    if (id && family) fonts.push({ id, family, license, weights });
  }
  ts.forEachChild(node, visit);
}

visit(sourceFile);

if (fonts.length !== 36) {
  throw new Error(`Expected exactly 36 font registry entries; found ${fonts.length}.`);
}

await mkdir(assetDirectory, { recursive: true });
await mkdir(path.dirname(lockPath), { recursive: true });

const userAgent = 'Mozilla/5.0 AppleWebKit/537.36 Chrome/125 Safari/537.36 MyBookNookFontBuilder/1.0';
const lock = { generatedAt: new Date().toISOString(), provider: 'Google Fonts', families: [] };
const css = [
  '/* Generated by scripts/sync-google-fonts.mjs. Do not edit by hand. */',
  '/* WOFF2 files are served locally; Google receives no runtime visitor requests. */',
];

for (const entry of fonts) {
  const familyQuery = entry.family.trim().replaceAll(' ', '+');
  const weightQuery = entry.weights.join(';');
  const stylesheetUrl = `https://fonts.googleapis.com/css2?family=${familyQuery}:wght@${weightQuery}&display=swap`;
  const stylesheetResponse = await fetch(stylesheetUrl, { headers: { 'User-Agent': userAgent } });
  if (!stylesheetResponse.ok) {
    throw new Error(`Google Fonts CSS failed for ${entry.family}: ${stylesheetResponse.status}`);
  }
  const stylesheet = await stylesheetResponse.text();
  const blocks = [...stylesheet.matchAll(/(?:\/\*\s*([^*]+?)\s*\*\/\s*)?@font-face\s*{([^}]+)}/g)];
  const familyLock = { id: entry.id, family: entry.family, license: entry.license, stylesheetUrl, files: [] };

  for (const weight of entry.weights) {
    const candidates = blocks.filter((match) => {
      const body = match[2];
      return new RegExp(`font-weight:\\s*${weight}(?:\\s*;|\\s*$)`).test(body);
    });
    const selected = candidates.find((match) => match[1]?.trim().toLowerCase() === 'latin') ?? candidates.at(-1);
    const assetUrl = selected?.[2].match(/src:\s*url\((https:\/\/[^)]+\.woff2)\)/)?.[1];
    if (!assetUrl) throw new Error(`No Latin WOFF2 located for ${entry.family} ${weight}.`);

    const assetResponse = await fetch(assetUrl, { headers: { 'User-Agent': userAgent } });
    if (!assetResponse.ok) throw new Error(`WOFF2 download failed for ${entry.family} ${weight}.`);
    const bytes = Buffer.from(await assetResponse.arrayBuffer());
    const filename = `${entry.id}-${weight}.woff2`;
    await writeFile(path.join(assetDirectory, filename), bytes);
    const sha256 = createHash('sha256').update(bytes).digest('hex');

    css.push(
      '',
      `@font-face {`,
      `  font-family: '${entry.family.replaceAll("'", "\\'")}';`,
      `  font-style: normal;`,
      `  font-weight: ${weight};`,
      `  font-display: swap;`,
      `  src: url('/fonts/${filename}') format('woff2');`,
      `}`,
    );
    familyLock.files.push({ weight, filename, sourceUrl: assetUrl, sha256, bytes: bytes.length, subset: 'latin' });
  }

  lock.families.push(familyLock);
}

await writeFile(cssPath, `${css.join('\n')}\n`);
await writeFile(lockPath, `${JSON.stringify(lock, null, 2)}\n`);
await writeFile(
  path.join(assetDirectory, 'LICENSES.md'),
  `# Font licenses\n\nThe fonts in this directory were downloaded from Google Fonts for My Book Nook.\nEach registry entry records its license and source. OFL fonts use the\n[SIL Open Font License 1.1](https://openfontlicense.org); Roboto Mono uses the\n[Apache License 2.0](https://www.apache.org/licenses/LICENSE-2.0).\n\nSee \`config/google-fonts.lock.json\` for exact source URLs and SHA-256 hashes.\n`,
);

console.log(`Pinned ${fonts.length} families and ${lock.families.reduce((sum, family) => sum + family.files.length, 0)} Latin WOFF2 files.`);
